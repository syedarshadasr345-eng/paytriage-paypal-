def seed_database(base_date: date = date.today()) -> int:
    """Populate SQLite database with benchmark demo records."""
    init_db()
    clear_invoices()
    records = get_seed_invoices(base_date)
    for inv in records:
        insert_invoice(inv)
    return len(records)


if __name__ == "__main__":
    count = seed_database()
    print(f"Successfully seeded {count} DEMO DATA invoices into SQLite database.")
