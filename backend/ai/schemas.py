"""
PayTriage AI — Pydantic Schemas for AI Service Layer
Strictly conforms to phase3.md and RULES.md (§4, §6).
Enforces fixed JSON contracts, grounded validation, and distinct operational states.
"""

from typing import List, Optional, Literal, Dict, Any
from pydantic import BaseModel, Field


# -----------------------------------------------------------------------------
# Explanation Schemas
# -----------------------------------------------------------------------------

class ExplanationRequest(BaseModel):
    """Optional user context or question when requesting an explanation."""
    question: Optional[str] = Field(None, description="Optional custom merchant question regarding this invoice.")


class ExplanationResponse(BaseModel):
    """Structured, grounded invoice recovery explanation.
    Conforms to phase3.md Step 2.
    """
    invoice_id: str = Field(..., description="Target invoice ID.")
    summary: str = Field(..., description="Concise explanation of recovery status and urgency.")
    key_factors: List[str] = Field(default_factory=list, description="Primary verified drivers of the priority score.")
    recommended_action: str = Field(..., description="Recommended next-best recovery action with justification.")
    unavailable_information: List[str] = Field(default_factory=list, description="Explicit list of data points not available.")
    caveats: List[str] = Field(default_factory=list, description="Decision-support disclaimers and operational boundaries.")
    source: Literal["ai", "template_fallback"] = Field(..., description="Whether generated by Gemini AI or deterministic fallback.")
    confidence_note: str = Field(..., description="Note clarifying decision-support boundaries.")
    generated_at: str = Field(..., description="ISO 8601 timestamp.")


# -----------------------------------------------------------------------------
# Reminder Generator Schemas
# -----------------------------------------------------------------------------

ReminderTone = Literal["professional", "friendly", "polite", "firm"]


class ReminderCreateRequest(BaseModel):
    """Request to generate a reminder draft for an invoice."""
    tone: ReminderTone = Field("polite", description="Tone of the reminder: professional, friendly, polite, or firm.")


class ReminderEditRequest(BaseModel):
    """Request to update an existing reminder draft."""
    subject: Optional[str] = Field(None, description="Updated email subject line.")
    body: Optional[str] = Field(None, description="Updated email body text.")


class ReminderDraftResponse(BaseModel):
    """Draft reminder model. Never says 'Reminder Sent'.
    Drafts are strictly distinct: draft -> copied.
    """
    id: str = Field(..., description="Unique draft identifier.")
    invoice_id: str = Field(..., description="Target invoice ID.")
    tone: str = Field(..., description="Tone used for this draft.")
    subject: str = Field(..., description="Subject line.")
    body: str = Field(..., description="Draft message body.")
    status: Literal["draft", "copied"] = Field("draft", description="Current draft state. Never 'sent'.")
    source: Literal["ai", "template_fallback"] = Field(..., description="Whether generated by Gemini or template.")
    created_at: str = Field(..., description="Creation ISO timestamp.")
    updated_at: str = Field(..., description="Last updated ISO timestamp.")


class ReminderCopyResponse(BaseModel):
    """Response returned when merchant copies reminder text to clipboard."""
    id: str
    invoice_id: str
    status: Literal["copied"]
    copied_text: str
    activity_log_id: str
    message: str = "Draft marked as copied. No email has been sent."


# -----------------------------------------------------------------------------
# Assistant Schemas
# -----------------------------------------------------------------------------

class AssistantMessageRequest(BaseModel):
    """Interactive merchant query to the recovery assistant."""
    message: str = Field(..., min_length=1, max_length=1000, description="Merchant query text.")
    conversation_id: Optional[str] = Field(None, description="Optional conversation tracking identifier.")


class AssistantResponse(BaseModel):
    """Structured assistant response with tool execution audit."""
    reply: str = Field(..., description="Helpful, grounded assistant response.")
    tools_used: List[str] = Field(default_factory=list, description="Backend tools invoked to answer the query.")
    referenced_invoices: List[str] = Field(default_factory=list, description="Verified invoice IDs referenced.")
    source: Literal["ai", "assistant_fallback"] = Field(..., description="AI agent response or grounded fallback.")
    conversation_id: Optional[str] = Field(None, description="Conversation tracking identifier.")
